CREATE TABLE users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    email VARCHAR(255),
    phone VARCHAR(32),
    timezone VARCHAR(64) NOT NULL,
    api_token VARCHAR(128) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT uq_users_email UNIQUE (email)
);
CREATE UNIQUE INDEX ix_users_api_token ON users (api_token);

CREATE TABLE alarms (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL,
    time VARCHAR(5) NOT NULL,
    label VARCHAR(120) NOT NULL,
    sound VARCHAR(64) NOT NULL,
    vibration VARCHAR(16) NOT NULL,
    repeat_pattern VARCHAR(64) NOT NULL,
    snooze_enabled BOOLEAN NOT NULL,
    verification_task_type VARCHAR(32) NOT NULL,
    custom_task_text CLOB,
    priority INTEGER NOT NULL,
    is_active BOOLEAN NOT NULL,
    status VARCHAR(32) NOT NULL,
    next_trigger_at TIMESTAMP,
    triggered_at TIMESTAMP,
    snooze_count INTEGER NOT NULL,
    failed_attempts INTEGER NOT NULL,
    camera_failures INTEGER NOT NULL,
    current_task CLOB,
    escalation_episode VARCHAR(64),
    updated_at TIMESTAMP NOT NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_alarms_user FOREIGN KEY (user_id) REFERENCES users (id)
);
CREATE INDEX ix_alarms_user_id ON alarms (user_id);

CREATE TABLE emergency_contacts (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL,
    name VARCHAR(120) NOT NULL,
    phone VARCHAR(32) NOT NULL,
    consent_status VARCHAR(16) NOT NULL,
    consent_token VARCHAR(64) NOT NULL,
    CONSTRAINT fk_contacts_user FOREIGN KEY (user_id) REFERENCES users (id)
);
CREATE UNIQUE INDEX ix_emergency_contacts_consent_token ON emergency_contacts (consent_token);
CREATE INDEX ix_emergency_contacts_user_id ON emergency_contacts (user_id);

CREATE TABLE notifications (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL,
    kind VARCHAR(32) NOT NULL,
    title VARCHAR(200) NOT NULL,
    body CLOB NOT NULL,
    data CLOB NOT NULL,
    is_read BOOLEAN NOT NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_notifications_user FOREIGN KEY (user_id) REFERENCES users (id)
);
CREATE INDEX ix_notifications_user_id ON notifications (user_id);

CREATE TABLE recommendations (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL,
    type VARCHAR(48) NOT NULL,
    title VARCHAR(200) NOT NULL,
    rationale CLOB NOT NULL,
    change CLOB NOT NULL,
    source VARCHAR(32) NOT NULL,
    status VARCHAR(16) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_recommendations_user FOREIGN KEY (user_id) REFERENCES users (id)
);
CREATE INDEX ix_recommendations_user_id ON recommendations (user_id);

CREATE TABLE reminder_logs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reminder_id INTEGER,
    user_id INTEGER NOT NULL,
    event VARCHAR(32) NOT NULL,
    level INTEGER,
    channel VARCHAR(16),
    category VARCHAR(16),
    details CLOB NOT NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_reminder_logs_user FOREIGN KEY (user_id) REFERENCES users (id)
);
CREATE INDEX ix_reminder_logs_reminder_id ON reminder_logs (reminder_id);
CREATE INDEX ix_reminder_logs_user_id ON reminder_logs (user_id);

CREATE TABLE reminders (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL,
    title VARCHAR(200) NOT NULL,
    notes CLOB,
    due_at TIMESTAMP NOT NULL,
    priority VARCHAR(16) NOT NULL,
    category VARCHAR(16) NOT NULL,
    repeat_pattern VARCHAR(16) NOT NULL,
    series_id VARCHAR(64),
    series_time VARCHAR(5),
    notification_type VARCHAR(16) NOT NULL,
    extra_times CLOB NOT NULL,
    status VARCHAR(16) NOT NULL,
    escalation_level INTEGER NOT NULL,
    first_notified_at TIMESTAMP,
    completed_at TIMESTAMP,
    snooze_count INTEGER NOT NULL,
    source VARCHAR(16) NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_reminders_user FOREIGN KEY (user_id) REFERENCES users (id)
);
CREATE INDEX ix_reminders_due_at ON reminders (due_at);
CREATE INDEX ix_reminders_series_id ON reminders (series_id);
CREATE INDEX ix_reminders_user_id ON reminders (user_id);

CREATE TABLE user_preferences (
    user_id INTEGER NOT NULL PRIMARY KEY,
    enabled_channels CLOB NOT NULL,
    escalation_order CLOB NOT NULL,
    notification_methods CLOB NOT NULL,
    quiet_hours_start VARCHAR(5),
    quiet_hours_end VARCHAR(5),
    checkin_enabled BOOLEAN NOT NULL,
    checkin_delay_minutes INTEGER NOT NULL,
    default_task_type VARCHAR(32) NOT NULL,
    push_token VARCHAR(255),
    category_preferred_times CLOB NOT NULL,
    suppressed_recommendation_types CLOB NOT NULL,
    dismissed_recommendation_counts CLOB NOT NULL,
    CONSTRAINT fk_prefs_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE user_profiles (
    user_id INTEGER NOT NULL PRIMARY KEY,
    escalation_stats CLOB NOT NULL,
    alarm_patterns CLOB NOT NULL,
    task_completion_rates CLOB NOT NULL,
    verification_stats CLOB NOT NULL,
    data_status VARCHAR(32) NOT NULL,
    skipped_rows INTEGER NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_profiles_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE alarm_logs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alarm_id INTEGER,
    user_id INTEGER NOT NULL,
    event VARCHAR(32) NOT NULL,
    task_type VARCHAR(32),
    details CLOB NOT NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_alarm_logs_alarm FOREIGN KEY (alarm_id) REFERENCES alarms (id),
    CONSTRAINT fk_alarm_logs_user FOREIGN KEY (user_id) REFERENCES users (id)
);
CREATE INDEX ix_alarm_logs_alarm_id ON alarm_logs (alarm_id);
CREATE INDEX ix_alarm_logs_user_id ON alarm_logs (user_id);

CREATE TABLE checkins (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alarm_id INTEGER,
    user_id INTEGER NOT NULL,
    scheduled_at TIMESTAMP NOT NULL,
    sent_at TIMESTAMP,
    responded_at TIMESTAMP,
    channel VARCHAR(16),
    status VARCHAR(16) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_checkins_alarm FOREIGN KEY (alarm_id) REFERENCES alarms (id),
    CONSTRAINT fk_checkins_user FOREIGN KEY (user_id) REFERENCES users (id)
);
CREATE INDEX ix_checkins_alarm_id ON checkins (alarm_id);
CREATE INDEX ix_checkins_user_id ON checkins (user_id);

CREATE TABLE escalation_logs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL,
    alarm_id INTEGER,
    episode VARCHAR(64) NOT NULL,
    attempt INTEGER NOT NULL,
    trigger_event VARCHAR(32) NOT NULL,
    method VARCHAR(32),
    decided_by VARCHAR(64) NOT NULL,
    reasoning CLOB NOT NULL,
    confidence DOUBLE,
    fallback_method VARCHAR(32),
    fallback_used BOOLEAN NOT NULL,
    inputs CLOB NOT NULL,
    status VARCHAR(16) NOT NULL,
    error CLOB,
    sent_at TIMESTAMP,
    responded_at TIMESTAMP,
    response_time_seconds DOUBLE,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_escalation_logs_alarm FOREIGN KEY (alarm_id) REFERENCES alarms (id),
    CONSTRAINT fk_escalation_logs_user FOREIGN KEY (user_id) REFERENCES users (id)
);
CREATE INDEX ix_escalation_logs_alarm_id ON escalation_logs (alarm_id);
CREATE INDEX ix_escalation_logs_episode ON escalation_logs (episode);
CREATE INDEX ix_escalation_logs_user_id ON escalation_logs (user_id);
